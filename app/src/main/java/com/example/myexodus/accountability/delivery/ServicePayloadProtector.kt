package com.example.myexodus.accountability.delivery

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * §8.1 local seal over sensitive queue source bytes. Deliberately independent of the App Lock
 * biometric key and of the signing key: a locked vault, a closed UI or an unattended background
 * service changes nothing here, and the key is never auth-bound.
 */
interface ServicePayloadProtector {
    /** Returns `iv || ciphertext+tag`; the IV is generated by the cipher, never supplied. */
    fun seal(aad: ByteArray, plaintext: ByteArray): ByteArray

    /** Inverse of [seal]; throws on a short/malformed buffer or AAD/tag mismatch. */
    fun open(aad: ByteArray, sealed: ByteArray): ByteArray
}

/**
 * Android Keystore AES-256-GCM. §8.1's IV rule is load-bearing: the cipher generates the IV,
 * and the IV the cipher reports is what gets stored ahead of the ciphertext — the caller never
 * reuses one.
 */
class KeystoreServicePayloadProtector : ServicePayloadProtector {

    override fun seal(aad: ByteArray, plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey())
        cipher.updateAAD(aad)
        return cipher.iv + cipher.doFinal(plaintext)
    }

    override fun open(aad: ByteArray, sealed: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(
            Cipher.DECRYPT_MODE,
            secretKey(),
            GCMParameterSpec(TAG_BITS, sealed, 0, IV_LENGTH),
        )
        cipher.updateAAD(aad)
        return cipher.doFinal(sealed, IV_LENGTH, sealed.size - IV_LENGTH)
    }

    private fun secretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEY_STORE).apply { load(null) }
        (keyStore.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }
        synchronized(GENERATION_LOCK) {
            (keyStore.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }
            val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEY_STORE)
            generator.init(
                KeyGenParameterSpec.Builder(
                    KEY_ALIAS,
                    KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                )
                    .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                    .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                    .setKeySize(256)
                    .setUserAuthenticationRequired(false)
                    .build(),
            )
            return generator.generateKey()
        }
    }

    companion object {
        /** §8.1 plan-specified alias. Keystore keys are non-backed-up by construction. */
        const val KEY_ALIAS = "myexodus.service.payload.aes.v1"

        private const val ANDROID_KEY_STORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val TAG_BITS = 128
        private const val IV_LENGTH = 12
        private val GENERATION_LOCK = Any()
    }
}
